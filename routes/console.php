<?php

use App\Models\Portfolio;
use Illuminate\Foundation\Inspiring;
use Illuminate\Support\Facades\Artisan;
use Illuminate\Support\Facades\Schedule;

Artisan::command('hci:summary', function () {
    $trackerPath = base_path('docs/HCI_TRACKER.md');
    $tracker = file_get_contents($trackerPath);
    preg_match_all('/^\|\s*([SNHUCVR]\d+)\s*\|([^\n]*)$/m', $tracker, $matches, PREG_SET_ORDER);

    $sets = [
        'S' => 'Shneiderman',
        'N' => 'Norman',
        'H' => 'Nielsen',
        'U' => 'Universal Design',
        'C' => 'Color theory',
        'V' => 'Visual design',
        'R' => 'User needs',
    ];
    $counts = [];
    $open = [];
    foreach ($matches as $match) {
        $cells = array_map('trim', explode('|', $match[0]));
        $cells = array_slice($cells, 1, -1);
        if (count($cells) !== 6) {
            continue;
        }
        $prefix = substr($cells[0], 0, 1);
        $status = $cells[5];
        $counts[$prefix][$status] = ($counts[$prefix][$status] ?? 0) + 1;
        if ($status !== 'Verified') {
            $open[] = '- **'.$cells[0].'** '.$cells[1].' — '.$status;
        }
    }

    $total = array_sum(array_map(fn ($set) => array_sum($set), $counts));
    $verified = array_sum(array_map(fn ($set) => $set['Verified'] ?? 0, $counts));
    $percentage = $total === 0 ? 0 : round($verified / $total * 100, 1);
    $lines = [
        '# HCI tracker summary',
        '',
        'Generated by `php artisan hci:summary` from `docs/HCI_TRACKER.md`.',
        '',
        '| Principle set | Planned | Implemented | Verified | Total |',
        '|---|---:|---:|---:|---:|',
    ];
    foreach ($sets as $prefix => $name) {
        $set = $counts[$prefix] ?? [];
        $setTotal = array_sum($set);
        $lines[] = '| '.$name.' | '.($set['Planned'] ?? 0).' | '.($set['Implemented'] ?? 0).' | '.($set['Verified'] ?? 0).' | '.$setTotal.' |';
    }
    $lines[] = '';
    $lines[] = '**Verified overall:** '.$verified.' / '.$total.' ('.$percentage.'%)';
    $lines[] = '';
    $lines[] = '## Open items';
    $lines[] = '';
    $lines = array_merge($lines, $open === [] ? ['None.'] : $open);
    $lines[] = '';

    file_put_contents(base_path('docs/HCI_TRACKER_SUMMARY.md'), implode("\n", $lines));
    $this->info('Wrote docs/HCI_TRACKER_SUMMARY.md ('.$verified.'/'.$total.' verified, '.$percentage.'%).');
})->purpose('Generate the HCI tracker status summary');

Artisan::command('portfolios:purge-expired', function () {
    $deleted = Portfolio::onlyTrashed()
        ->whereNotNull('undo_until')
        ->where('undo_until', '<=', now())
        ->forceDelete();

    $this->info("Permanently removed {$deleted} expired portfolio(s).");
})->purpose('Permanently remove portfolios whose undo period has ended');

Schedule::command('portfolios:purge-expired')->everyTenSeconds()->withoutOverlapping();

Artisan::command('inspire', function () {
    $this->comment(Inspiring::quote());
})->purpose('Display an inspiring quote')->hourly();
